"""Writes src/data.asm (every ROM asset, one section per group so each fits a
32KB LoROM bank) and src/assets.c (per-stage asset pointers for the game).
Run it after adding or renaming assets; both outputs are checked in.
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
NSTAGES = 6


def section(name, entries):
    out = [f'.section ".rodata_{name}" superfree', ""]
    for label, path, end in entries:
        out.append(f"{label}:")
        out.append(f'.incbin "build/{path}"')
        if end:
            out.append(f"{label}_end:")
        out.append("")
    out.append(".ends")
    out.append("")
    return "\n".join(out)


def main():
    parts = ['.include "hdr.asm"', ""]
    for n in range(1, NSTAGES + 1):
        p = f"st{n}"
        parts.append(f"; Stage {n} " + "-" * 60)
        parts.append(section(f"{p}_map", [(f"{p}_map", f"{p}.m16", False)]))
        parts.append(section(f"{p}_tiles", [(f"{p}_bg1_pic", f"{p}_bg1.pic", True),
                                             (f"{p}_tiledef", f"{p}.t16", False),
                                             (f"{p}_tileprop", f"{p}.b16", False),
                                             (f"{p}_bg_pal", f"{p}_bg.pal", False),
                                             (f"{p}_hero", f"{p}_hero.o16", False)]))
        parts.append(section(f"{p}_bg2", [(f"{p}_bg2_pic", f"{p}_bg2.pic", True),
                                           (f"{p}_bg2_map", f"{p}_bg2.map", False)]))
        parts.append(section(f"{p}_spr", [(f"{p}_foes", f"{p}_foes.pic", False),
                                           (f"{p}_small", f"{p}_small.pic", False),
                                           (f"{p}_boss", f"{p}_boss.pic", False),
                                           (f"{p}_spra", f"{p}_spra.pal", False),
                                           (f"{p}_sprb", f"{p}_sprb.pal", False),
                                           (f"{p}_bosspal", f"{p}_boss.pal", False)]))
    parts.append("; Title screen and UI " + "-" * 50)
    parts.append(section("ui", [("logo_pic", "logo.pic", True), ("logo_pal", "logo.pal", False),
                                ("title_bg1_map", "title_bg1.map", False), ("font_pic", "font.pic", True),
                                ("ui_pal", "ui.pal", False)]))
    parts.append("; Pickups, props and weapon shots " + "-" * 37)
    parts.append(section("items", [("items_pic", "items.pic", False), ("items_pal", "items.pal", False),
                                   ("boom_pic", "boom.pic", False)]))
    parts.append("; Heroes " + "-" * 62)
    parts.append(section("jon", [("jon_pic", "jon.pic", False), ("jon_pal", "jon.pal", False),
                                 ("jon_dim_pal", "jon_dim.pal", False)]))
    parts.append(section("wes", [("wes_pic", "wes.pic", False), ("wes_pal", "wes.pal", False),
                                 ("wes_dim_pal", "wes_dim.pal", False)]))
    parts.append("; Road Ride " + "-" * 59)
    parts.append(section("race_spr", [("race_big", "race_big.pic", False), ("race_small", "race_small.pic", False),
                                      ("jonbike_pal", "jonbike.pal", False), ("wesbike_pal", "wesbike.pal", False),
                                      ("bonus_obj_pal", "bonus_obj.pal", False)]))
    parts.append(section("race_bg", [("race_bg1_pic", "race_bg1.pic", True), ("race_bg1_map", "race_bg1.map", False),
                                     ("race_bg2_pic", "race_bg2.pic", True), ("race_bg2_map", "race_bg2.map", False),
                                     ("race_bg_pal", "race_bg.pal", False),
                                     ("race_bg_night_pal", "race_bg_night.pal", False),
                                     ("race_bg_dusk_pal", "race_bg_dusk.pal", False)]))
    parts.append("; The Range " + "-" * 59)
    parts.append(section("range_bg", [("range_bg1_pic", "range_bg1.pic", True), ("range_bg1_map", "range_bg1.map", False),
                                      ("range_bg_pal", "range_bg.pal", False),
                                      ("range_bg_dusk_pal", "range_bg_dusk.pal", False),
                                      ("range_big", "range_big.pic", False), ("range_small", "range_small.pic", False)]))
    parts.append(section("range_bg2", [("range_bg2_pic", "range_bg2.pic", True),
                                       ("range_bg2_map", "range_bg2.map", False)]))
    with open(os.path.join(ROOT, "src", "data.asm"), "w") as f:
        f.write("; generated by tools/gen_data.py\n")
        f.write("\n".join(parts))

    # assets.c: extern declarations and a per-stage loader
    names = ["map", "bg1_pic", "bg1_pic_end", "tiledef", "tileprop", "bg_pal", "hero", "bg2_pic", "bg2_pic_end",
             "bg2_map", "foes", "small", "boss", "spra", "sprb", "bosspal"]
    c = ["// generated by tools/gen_data.py", '#include "game.h"', "",
         "char *a_map, *a_bg1pic, *a_tiledef, *a_tileprop, *a_bgpal, *a_hero;",
         "char *a_bg2pic, *a_bg2map, *a_foes, *a_small, *a_boss, *a_spra, *a_sprb, *a_bosspal;",
         "u16 a_bg1size, a_bg2size;",
         "u16 *a_foetab, *a_hearttab, *a_proptab, *a_cptab, *a_gadtab;",
         "u16 a_nfoes, a_nhearts, a_nprops, a_arenax, a_ngads;", ""]
    for n in range(1, NSTAGES + 1):
        c.append("extern char " + ", ".join(f"st{n}_{k}" for k in names) + ";")
    c.append("")
    for n in range(1, NSTAGES + 1):
        c.append(f'#include "build/st{n}_info.h"')
    c.append("")
    c.append("void loadStageAssets(u8 s)")
    c.append("{")
    c.append("    switch (s)")
    c.append("    {")
    for n in range(1, NSTAGES + 1):
        p = f"st{n}"
        c.append(f"    case {n - 1}:")
        c.append(f"        a_map = &{p}_map;")
        c.append(f"        a_bg1pic = &{p}_bg1_pic;")
        c.append(f"        a_bg1size = &{p}_bg1_pic_end - &{p}_bg1_pic;")
        c.append(f"        a_tiledef = &{p}_tiledef;")
        c.append(f"        a_tileprop = &{p}_tileprop;")
        c.append(f"        a_bgpal = &{p}_bg_pal;")
        c.append(f"        a_hero = &{p}_hero;")
        c.append(f"        a_bg2pic = &{p}_bg2_pic;")
        c.append(f"        a_bg2size = &{p}_bg2_pic_end - &{p}_bg2_pic;")
        c.append(f"        a_bg2map = &{p}_bg2_map;")
        c.append(f"        a_foes = &{p}_foes;")
        c.append(f"        a_small = &{p}_small;")
        c.append(f"        a_boss = &{p}_boss;")
        c.append(f"        a_spra = &{p}_spra;")
        c.append(f"        a_sprb = &{p}_sprb;")
        c.append(f"        a_bosspal = &{p}_bosspal;")
        c.append(f"        a_foetab = (u16 *){p}_foetab;")
        c.append(f"        a_hearttab = (u16 *){p}_hearttab;")
        c.append(f"        a_nfoes = ST{n}_NFOES;")
        c.append(f"        a_nhearts = ST{n}_NHEARTS;")
        c.append(f"        a_proptab = (u16 *){p}_proptab;")
        c.append(f"        a_cptab = (u16 *){p}_cptab;")
        c.append(f"        a_nprops = ST{n}_NPROPS;")
        c.append(f"        a_gadtab = (u16 *){p}_gadtab;")
        c.append(f"        a_ngads = ST{n}_NGADS;")
        c.append(f"        a_arenax = ST{n}_ARENA_X;")
        c.append("        break;")
    c.append("    }")
    c.append("}")
    with open(os.path.join(ROOT, "src", "assets.c"), "w") as f:
        f.write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
